def is_default_avatar(avatar_id: object) -> bool:
    """True when the id is one of VRChat's built-in default avatars."""
    if not isinstance(avatar_id, str):
        return False
    return avatar_id.strip().lower() in DEFAULT_AVATAR_IDS


def is_default_avatar_name(name: object) -> bool:
    """True when a player-change name is a known default avatar.

    Exact match after case folding, never a substring: "Robot Deluxe" and
    "Papyrus Mark II" are ordinary community avatars and must survive. Only a
    name identical to a default is dropped.
    """
    if not isinstance(name, str):
        return False
    return name.strip().casefold() in DEFAULT_AVATAR_NAMES


